package com.webicSoftIndia.HRMS.PasswordHistory;

import com.webicSoftIndia.HRMS.common.ApiResponse;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/v1/password-history")
@RequiredArgsConstructor
public class PasswordHistoryController {

    private final PasswordHistoryService passwordHistoryService;

    @PostMapping("/create")
    public ResponseEntity<ApiResponse<PasswordHistory>> createOrUpdatePasswordHistory(@RequestBody PasswordHistory passwordHistory) {
        ApiResponse<PasswordHistory> response = passwordHistoryService.saveOrUpdatePasswordHistory(passwordHistory);
        if (response.isSuccess()) {
            return ResponseEntity.ok(response);
        } else {
            return ResponseEntity.badRequest().body(response);
        }
    }

    @PostMapping("/list")
    public ResponseEntity<ApiResponse<List<PasswordHistory>>> listPasswordHistory(
            @RequestHeader(value = "X-Session-ID", required = false) String xSessionId,
            @RequestHeader(value = "Session-ID", required = false) String sessionIdHeader,
            @RequestHeader(value = "sessionId", required = false) String sessionIdParam) {

        String targetSessionId = null;
        if (xSessionId != null && !xSessionId.trim().isEmpty()) {
            targetSessionId = xSessionId.trim();
        } else if (sessionIdHeader != null && !sessionIdHeader.trim().isEmpty()) {
            targetSessionId = sessionIdHeader.trim();
        } else if (sessionIdParam != null && !sessionIdParam.trim().isEmpty()) {
            targetSessionId = sessionIdParam.trim();
        }

        ApiResponse<List<PasswordHistory>> response = passwordHistoryService.getPasswordHistoryBySessionUnit(targetSessionId);
        if (response.isSuccess()) {
            return ResponseEntity.ok(response);
        } else {
            return ResponseEntity.badRequest().body(response);
        }
    }
}
